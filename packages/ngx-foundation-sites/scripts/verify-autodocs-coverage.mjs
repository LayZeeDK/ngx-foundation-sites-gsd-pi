// R007 gate: the Storybook autodocs ArgTypes table really does document every
// NfsButton input.
//
// Ticket 15 found the table empty -- `color` typed `string`, every other input
// a bare `-` -- on a GREEN build. `test-storybook` fails only on browser
// console errors and the defect emitted none, so nothing anywhere in the
// battery noticed. Three independent parts have to line up for the table to
// populate, and any one of them regressing silently empties it again:
//
//   1. `compodoc: true` on the Storybook targets -- without it no docgen JSON
//      is produced at all.
//   2. `compodocArgs` pinning `-p tsconfig.lib.json` -- the builder otherwise
//      defaults to `.storybook/tsconfig.json`, whose `include` covers only
//      `*.stories.ts`, measured to emit `components: []`.
//   3. `setCompodocJson` in `.storybook/preview.ts` -- Storybook's Angular
//      renderer reads `globalThis.__STORYBOOK_COMPODOC_JSON__` and nothing
//      else populates it.
//
// Parts 1 and 2 are asserted against the GENERATED artifact, which is where
// they actually fail; a headless render per build would be disproportionate.
// The artifact is gitignored and regenerated by `build-storybook`, so this
// target depends on that one rather than on a committed file.
//
// ponytail: part 3 leaves no trace in the artifact -- a perfect
// documentation.json feeds an empty table when the wire is cut -- so it is
// asserted against `preview.ts` source instead. That is a shape check, and the
// weakest assertion here; the rendered-page proof stays a manual step (ticket
// 15's Playwright pass over /?path=/docs/nfsbutton--docs).
import { existsSync, readFileSync } from 'node:fs';

const DOC_PATH = 'packages/ngx-foundation-sites/documentation.json';
const PREVIEW_PATH = 'packages/ngx-foundation-sites/.storybook/preview.ts';
const COMPONENT_NAME = 'NfsButton';
const REQUIRED_INPUTS = [
  'color',
  'hollow',
  'size',
  'expanded',
  'dropdown',
  'disabled',
];

const COMPODOC_FLAG =
  'likely cause: `compodoc: true` is no longer set on the `storybook` and ' +
  '`build-storybook` targets in packages/ngx-foundation-sites/project.json, ' +
  'so no docgen ran (or this check ran before `build-storybook` did).';
const COMPODOC_ARGS =
  'likely cause: the `compodocArgs` tsconfig pin ' +
  '(`-p packages/ngx-foundation-sites/tsconfig.lib.json`) is missing or wrong ' +
  "in packages/ngx-foundation-sites/project.json. The builder's default, " +
  '.storybook/tsconfig.json, includes only *.stories.ts and emits ' +
  '`components: []`.';
const SET_COMPODOC_JSON =
  `likely cause: ${PREVIEW_PATH} no longer calls \`setCompodocJson(docJson)\`, ` +
  'so `globalThis.__STORYBOOK_COMPODOC_JSON__` stays unset and the ArgTypes ' +
  'table renders every input as `-` no matter how good the docgen JSON is.';

const failures = [];

function fail(message, cause) {
  failures.push({ message, cause });
}

function report() {
  if (failures.length > 0) {
    console.error('Autodocs coverage check FAILED:');

    for (const { message, cause } of failures) {
      console.error(`  ${message}`);
      console.error(`    ${cause}`);
    }

    process.exit(1);
  }
}

// Part 3 first: it is independent of the artifact, so a missing artifact must
// not hide it.
if (!readFileSync(PREVIEW_PATH, 'utf8').includes('setCompodocJson(')) {
  fail(`${PREVIEW_PATH} does not call setCompodocJson`, SET_COMPODOC_JSON);
}

if (!existsSync(DOC_PATH)) {
  fail(`${DOC_PATH} does not exist`, COMPODOC_FLAG);
  report();
}

const documentation = JSON.parse(readFileSync(DOC_PATH, 'utf8'));
const components = documentation.components ?? [];
const component = components.find((entry) => entry.name === COMPONENT_NAME);

if (components.length === 0) {
  fail(`${DOC_PATH} documents zero components`, COMPODOC_ARGS);
  report();
}

if (!component) {
  fail(
    `${COMPONENT_NAME} is absent from ${DOC_PATH} (documented components: ${components
      .map((entry) => entry.name)
      .join(', ')})`,
    COMPODOC_ARGS,
  );
  report();
}

if (!component.description?.trim()) {
  fail(
    `${COMPONENT_NAME} has no component-level description`,
    'likely cause: the class JSDoc on NfsButton was removed. Since ticket 16 ' +
      'deleted `parameters.docs.description.component` from nfs-button.stories.ts, ' +
      'that JSDoc is the only source of the docs page description.',
  );
}

const inputs = new Map(
  (component.inputsClass ?? []).map((input) => [input.name, input]),
);

for (const name of REQUIRED_INPUTS) {
  const input = inputs.get(name);

  if (!input) {
    fail(
      `${COMPONENT_NAME} input \`${name}\` is not documented (documented inputs: ${[...inputs.keys()].join(', ') || 'none'})`,
      `${COMPODOC_ARGS} If the pin is intact, the input was renamed or removed from nfs-button.ts.`,
    );
    continue;
  }

  if (!input.description?.trim()) {
    fail(
      `${COMPONENT_NAME} input \`${name}\` has an empty description`,
      'likely cause: its JSDoc comment was dropped from nfs-button.ts. Compodoc ' +
        'found the input but had no prose to attach, so autodocs renders a blank ' +
        'description cell.',
    );
  }
}

report();

console.log(
  [
    'Autodocs coverage check PASSED.',
    `  ${components.length} component(s) documented in ${DOC_PATH}`,
    `  ${COMPONENT_NAME}: ${REQUIRED_INPUTS.length} required inputs documented with non-empty descriptions`,
    `  ${PREVIEW_PATH} wires the docgen JSON via setCompodocJson`,
  ].join('\n'),
);
